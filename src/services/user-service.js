// services/user-service.js
const bcrypt = require("bcryptjs");
const jwt = require("jsonwebtoken");
const User = require("../models/user.model"); // your original model
// Allowed roles (if needed elsewhere)
const allowedRoles = ["admin", "partner", "franchise", "customer"];

// Keep validators here as requested
exports.isValidEmail = (email) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);

exports.isValidPassword = (password) =>
  typeof password === "string" &&
  password.length >= 8 &&
  /[a-z]/.test(password) &&
  /[A-Z]/.test(password) &&
  /\d/.test(password) &&
  /[!@#$%^&*(),.?":{}|<>]/.test(password);

// Create user
exports.createUser = async ({ email, password, selectedPlan }) => {
  try {
    const cleanEmail = email.trim().toLowerCase();

    const existingUser = await User.findOne({ email: cleanEmail });
    if (existingUser) throw new Error("EMAIL_EXISTS");

    const hashedPassword = await bcrypt.hash(password, 10);

    const user = await User.create({
      email: cleanEmail,
      password: hashedPassword,
      role: selectedPlan ? "customer" : "",
      isActive: true,
      registrationComplete: false,
    });

    return user;
  } catch (error) {
    console.error("Error in createUser:", error);
    throw error;
  }
};

// Find by email
